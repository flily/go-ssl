package hmac

import (
	"testing"

	"bytes"
	"crypto/hmac"
	"crypto/md5"
	"crypto/sha256"
	"hash"
)

type TestVectorStandard struct {
	Hash   func() hash.Hash
	Key    []byte
	Data   []byte
	Digest []byte
}

func (v TestVectorStandard) GetDigest() []byte {
	return HMAC(v.Hash, v.Key, v.Data)
}

func (v TestVectorStandard) Run(t *testing.T) {
	got := v.GetDigest()
	if !bytes.Equal(got, v.Digest) {
		t.Errorf("HMAC mismatch")
		t.Logf("expect: %x", v.Digest)
		t.Logf("got   : %x", got)
	}

	h := hmac.New(v.Hash, v.Key)
	_, _ = h.Write(v.Data)
	got2 := h.Sum(nil)
	if !bytes.Equal(got2, v.Digest) {
		t.Errorf("HMAC mismatch (using crypto/hmac)")
		t.Logf("expect: %x", v.Digest)
		t.Logf("got   : %x", got2)
	}
}

